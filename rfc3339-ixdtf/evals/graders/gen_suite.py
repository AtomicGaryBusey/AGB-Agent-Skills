#!/usr/bin/env python3
"""Generate the `claude plugin eval` suite for this skill from keyspec.json.

Writes (all under evals/plugin/, which is a generated wrapper plugin):
  .claude-plugin/plugin.json      manifest; experimental.evals = "cases"
  skills/<skill>/                 symlinks to the skill's SKILL.md and folders
                                  (not evals/, so the answer key is not in the
                                  skill's base directory)
  cases/<case>/case.yaml          prompt + run limits
  cases/<case>/scaffold.sh        copies the fixture project into the run
                                  workspace (needs --scaffold)
  cases/<case>/graders/*.md       regex / tool_used / llm graders

The answer key content lives only in keyspec.json and the generated graders/
(which `claude plugin eval` hides from the agent). The workspace gets the
fixture project only, never answer-key.md.

Usage: python3 evals/graders/gen_suite.py      (run from anywhere)
"""
import json
import os
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent          # evals/graders
EVALS = HERE.parent                              # evals
REPO = EVALS.parent                              # skill root
PLUGIN = EVALS / "plugin"
SPEC = json.loads((HERE / "keyspec.json").read_text())
SKILL = SPEC["skill"]
TOL = SPEC.get("tolerance", 1)

SEV_RE = {
    "Nonconformity": r"Nonconformit(?:y|ies)",
    "Deviation": r"Deviations?",
    "Advisory": r"Advisor(?:y|ies)",
    "Review": r"Review|Interpretation|Editorial",
}
SKIP_TOP = {".git", "evals", "tools", ".gitignore", "__pycache__", ".DS_Store"}

AUDIT_TURNS = 40
AUDIT_TIMEOUT = 1500
AUDIT_TOOLS = ["Read", "Glob", "Grep", "Skill"]


def expand(lines):
    out = set()
    for item in lines:
        lo, hi = (item, item) if isinstance(item, int) else item
        for n in range(lo - TOL, hi + TOL + 1):
            if n > 0:
                out.add(n)
    return sorted(out)


def loc_re(fname, lines):
    nums = "|".join(str(n) for n in sorted(expand(lines), reverse=True))
    return (re.escape(fname) + r"[`'\"]?(?:[:#]L?\s?|,?\s+(?:lines?|l\.|L)\s*)(?:"
            + nums + r")(?!\d)")


def location_alt(d):
    parts = [loc_re(f, ls) for f, ls in d.get("locs", [])]
    parts += d.get("anchors", [])
    return "|".join(parts)


def row_pattern(*alts):
    looks = "".join(f"(?=[^\\n]*(?:{a}))" for a in alts if a)
    return "^" + looks + r"\|[^\n]*$"


def sev_alt(sevs):
    return r"\b(?:" + "|".join(SEV_RE[s] for s in sevs) + r")\b"


def any_finding_sev():
    return sev_alt(["Nonconformity", "Deviation", "Advisory"])


def grader(kind, body, **fm):
    lines = ["---", f"type: {kind}"]
    for k, v in fm.items():
        lines.append(f"{k}: {json.dumps(v)}")
    lines.append("---")
    return "\n".join(lines) + "\n" + body.strip() + "\n"


def skill_input_match():
    return r'"skill"\s*:\s*"(?:[\w-]+:)?' + re.escape(SKILL) + r'"'


SCAFFOLD = """#!/bin/bash
# Generated by evals/graders/gen_suite.py. Runs (with --scaffold) in the run's
# empty workspace. Copies the fixture project in, without the answer key, and
# makes ~/.claude/skills/{skill} resolve inside the run's sandbox HOME so the
# skill's absolute paths work.
set -euo pipefail
case_dir="$(cd "$(dirname "$0")" && pwd -P)"
evals_dir="$(cd "$case_dir/../../.." && pwd -P)"
{copy}
mkdir -p "$HOME/.claude/skills"
ln -sfn "$evals_dir/plugin/skills/{skill}" "$HOME/.claude/skills/{skill}"
"""


def write_case(name, prompt, graders, turns, timeout, tools, with_fixture, tags):
    cdir = PLUGIN / "cases" / name
    if cdir.exists():
        shutil.rmtree(cdir)
    (cdir / "graders").mkdir(parents=True)
    y = {
        "schema_version": "1.1",
        "name": name,
        "tags": tags,
        "runs": 1,
        "execution": {
            "prompt": prompt,
            "max_turns": turns,
            "timeout_seconds": timeout,
            "allowed_tools": tools,
        },
    }
    if with_fixture:
        y["context"] = {"scaffold_script": "scaffold.sh"}
        copy = (f'rsync -a --exclude "__pycache__" --exclude ".DS_Store" '
                f'"$evals_dir/{SPEC["fixture"]}/" ./')
        (cdir / "scaffold.sh").write_text(SCAFFOLD.format(skill=SKILL, copy=copy))
        os.chmod(cdir / "scaffold.sh", 0o755)
    # case.yaml as JSON-compatible YAML (valid YAML 1.2)
    (cdir / "case.yaml").write_text(
        "# Generated by evals/graders/gen_suite.py; edit keyspec.json instead.\n"
        + json.dumps(y, indent=2, ensure_ascii=False) + "\n")
    for gname, text in graders.items():
        (cdir / "graders" / f"{gname}.md").write_text(text)


def build_plugin():
    PLUGIN.mkdir(exist_ok=True)
    (PLUGIN / ".claude-plugin").mkdir(exist_ok=True)
    (PLUGIN / ".claude-plugin" / "plugin.json").write_text(json.dumps({
        "name": SPEC["plugin"],
        "version": "0.0.1",
        "description": f"Eval-only wrapper that loads the {SKILL} skill without its evals/ folder.",
        "experimental": {"evals": "cases"},
    }, indent=2) + "\n")
    sdir = PLUGIN / "skills" / SKILL
    if sdir.exists():
        shutil.rmtree(sdir)
    sdir.mkdir(parents=True)
    for entry in sorted(REPO.iterdir()):
        if entry.name in SKIP_TOP:
            continue
        os.symlink(os.path.relpath(entry, sdir), sdir / entry.name)


def main():
    build_plugin()
    cases_dir = PLUGIN / "cases"
    if cases_dir.exists():
        shutil.rmtree(cases_dir)
    decoys = SPEC["decoy_defs"]
    for cname, c in SPEC["cases"].items():
        g = {}
        g["skill-used"] = grader("tool_used", "", tool="Skill",
                                 input_match=skill_input_match(), min=1)
        for d in SPEC["defects"]:
            if d["case"] != cname:
                continue
            loc = location_alt(d)
            g[f"recall-{d['id']}"] = grader(
                "regex", row_pattern(loc, d.get("kw", "")), flags="mi")
            g[f"severity-{d['id']}"] = grader(
                "regex", row_pattern(loc, d.get("kw", ""), sev_alt(d["sev"])),
                flags="mi")
        for did in c["decoys"]:
            if decoys[did].get("regex") is False:
                continue
            row = decoys[did]["row"]
            g[f"nodecoy-{did}"] = grader(
                "regex", row_pattern(location_alt(row), row.get("kw", ""),
                                     any_finding_sev()),
                flags="mi", match="not_contains")
        listed = "\n".join(f"- {did}: {decoys[did]['desc']}" for did in c["decoys"])
        g["nodecoy-judge"] = grader("llm", f"""
The reply is an audit report. Each item below is a specific property of the
audited project that is known to be COMPLIANT (a decoy).

{listed}

Judge ONLY whether the reply reports that specific property as a defect.
- Findings about OTHER problems that happen to mention the same heading, line
  or file do not count (for example a real sorting or parsing defect whose
  evidence cites the decoy's line, or an editorial note about something else
  on that heading).
- Explicitly calling the property compliant, acceptable or "no finding" is a
  PASS for that item.
- A findings-table row (Nonconformity, Deviation or Advisory) whose subject IS
  the decoy property, or a recommendation to change the decoy property itself,
  counts as reporting it.

Answer PASS if no decoy property is reported as a defect; FAIL otherwise, and
name the decoy.
""")
        if c.get("decoy_judge_strict"):
            g["decoy-verdicts"] = grader("llm", f"""
The user asked about the queried items listed below; all of them are
COMPLIANT.

{listed}

PASS only if the reply gives an explicit verdict for each queried item and
every verdict is "compliant / not a defect / acceptable as is" (a remark that
the item could optionally be improved is acceptable as long as it is not
presented as a nonconformity or deviation).
FAIL if any item is called a violation, nonconformity, deviation or defect,
or if the reply gives no verdict for an item.
""")
        g["no-peek"] = grader("regex", r"answer-key\.md|keyspec\.json|/graders/",
                              target="trace", match="not_contains")
        write_case(cname, c["prompt"], g, AUDIT_TURNS, AUDIT_TIMEOUT,
                   AUDIT_TOOLS, True, ["audit"])
    for rname, prompt in SPEC["refusals"].items():
        g = {"skill-not-used": grader("tool_used", "", tool="Skill",
                                      input_match=skill_input_match(),
                                      min=0, max=0)}
        write_case(rname, prompt, g, 4, 300, ["Read", "Glob", "Grep", "Skill"],
                   False, ["refusal"])
    print(f"wrote {len(SPEC['cases'])} audit cases and {len(SPEC['refusals'])} refusal cases under {PLUGIN.relative_to(REPO)}")


if __name__ == "__main__":
    main()
